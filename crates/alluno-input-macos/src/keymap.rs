//! The `CGKeyCode` half of the key table, on the ANSI layout.

use alluno_input_core::Key;

/// The virtual key code for a key.
pub fn to_keycode(key: Key) -> u16 {
    match key {
        Key::A => 0x00,
        Key::S => 0x01,
        Key::D => 0x02,
        Key::F => 0x03,
        Key::H => 0x04,
        Key::G => 0x05,
        Key::Z => 0x06,
        Key::X => 0x07,
        Key::C => 0x08,
        Key::V => 0x09,
        Key::B => 0x0B,
        Key::Q => 0x0C,
        Key::W => 0x0D,
        Key::E => 0x0E,
        Key::R => 0x0F,
        Key::Y => 0x10,
        Key::T => 0x11,
        Key::O => 0x1F,
        Key::U => 0x20,
        Key::I => 0x22,
        Key::P => 0x23,
        Key::L => 0x25,
        Key::J => 0x26,
        Key::K => 0x28,
        Key::N => 0x2D,
        Key::M => 0x2E,
        Key::Num1 => 0x12,
        Key::Num2 => 0x13,
        Key::Num3 => 0x14,
        Key::Num4 => 0x15,
        Key::Num5 => 0x17,
        Key::Num6 => 0x16,
        Key::Num7 => 0x1A,
        Key::Num8 => 0x1C,
        Key::Num9 => 0x19,
        Key::Num0 => 0x1D,
        Key::F1 => 0x7A,
        Key::F2 => 0x78,
        Key::F3 => 0x63,
        Key::F4 => 0x76,
        Key::F5 => 0x60,
        Key::F6 => 0x61,
        Key::F7 => 0x62,
        Key::F8 => 0x64,
        Key::F9 => 0x65,
        Key::F10 => 0x6D,
        Key::F11 => 0x67,
        Key::F12 => 0x6F,
        Key::Enter => 0x24,
        Key::Space => 0x31,
        Key::Tab => 0x30,
        Key::Escape => 0x35,
        Key::Backspace => 0x33,
        Key::Delete => 0x75,
        Key::Home => 0x73,
        Key::End => 0x77,
        Key::PageUp => 0x74,
        Key::PageDown => 0x79,
        Key::Left => 0x7B,
        Key::Right => 0x7C,
        Key::Down => 0x7D,
        Key::Up => 0x7E,
        Key::CapsLock => 0x39,
        Key::Insert => 0x72,
        Key::Pause => 0x71,
        Key::Minus => 0x1B,
        Key::Equal => 0x18,
        Key::BracketLeft => 0x21,
        Key::BracketRight => 0x1E,
        Key::Semicolon => 0x29,
        Key::Quote => 0x27,
        Key::Backslash => 0x2A,
        Key::Comma => 0x2B,
        Key::Period => 0x2F,
        Key::Slash => 0x2C,
        Key::Backquote => 0x32,
        Key::Numpad0 => 0x52,
        Key::Numpad1 => 0x53,
        Key::Numpad2 => 0x54,
        Key::Numpad3 => 0x55,
        Key::Numpad4 => 0x56,
        Key::Numpad5 => 0x57,
        Key::Numpad6 => 0x58,
        Key::Numpad7 => 0x59,
        Key::Numpad8 => 0x5B,
        Key::Numpad9 => 0x5C,
        Key::NumpadDecimal => 0x41,
        Key::NumpadMultiply => 0x43,
        Key::NumpadAdd => 0x45,
        Key::NumpadSubtract => 0x4E,
        Key::NumpadDivide => 0x4B,
        Key::NumpadEnter => 0x4C,
        Key::ShiftLeft => 0x38,
        Key::ShiftRight => 0x3C,
        Key::ControlLeft => 0x3B,
        Key::ControlRight => 0x3E,
        Key::AltLeft => 0x3A,
        Key::AltRight => 0x3D,
        Key::Meta => 0x37,
        _ => 0x35,
    }
}
